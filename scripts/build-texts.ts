// Builds the English dictionary the game reads (src/i18n/dictionary.en.ts) from the catalogues
// of texts: src/texts/fr/<area>.ts holds the French, src/texts/en/<area>.ts the English under
// the same names, and src/texts/en/recomposed.ts the few phrases that have no constant.
//   npm run texts:build             writes the dictionary
//   npm run texts:build -- --check  fails if the file on disk is not up to date
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const DICTIONARY = 'src/i18n/dictionary.en.ts';
/** The key the translator looks a text up by: its words, single-spaced (i18n/copy.ts). */
const lookup = (text: string) => text.trim().replace(/\s+/g, ' ');
const load = (file: string): Promise<Record<string, unknown>> => import(pathToFileURL(file).href);

/** The dictionary as a map, and every reason the catalogues do not agree. */
export async function buildDictionary() {
  const areas = (await readdir('src/texts/fr')).filter((name) => name.endsWith('.ts')).sort();
  const dictionary = new Map<string, string>();
  const faults: string[] = [];
  const add = (french: string, english: string, where: string) => {
    const key = lookup(french);
    const known = dictionary.get(key);
    if (known !== undefined && known !== english)
      faults.push(`« ${key} » has two English texts: « ${known} » and « ${english} » (${where})`);
    dictionary.set(key, english);
  };
  for (const area of areas) {
    const french = await load(`src/texts/fr/${area}`);
    const english = await load(`src/texts/en/${area}`).catch(() => null);
    if (!english) {
      faults.push(`src/texts/en/${area} is missing`);
      continue;
    }
    for (const [name, words] of Object.entries(french)) {
      const translated = english[name];
      if (typeof words !== 'string') faults.push(`${area}: « ${name} » is not a text`);
      else if (typeof translated !== 'string') faults.push(`${area}: no English for « ${name} »`);
      else add(words, translated, `${area} ${name}`);
    }
    for (const name of Object.keys(english))
      if (!(name in french)) faults.push(`${area}: English « ${name} » has no French`);
  }
  const { recomposedEnglish } = await load('src/texts/en/recomposed.ts');
  for (const [french, english] of Object.entries(recomposedEnglish as Record<string, string>))
    add(french, english, 'recomposed');
  return { dictionary, faults };
}

/** The file as it must be written: one line per text, in the order of the French words. */
export function dictionarySource(dictionary: ReadonlyMap<string, string>): string {
  const lines = [...dictionary]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([french, english]) => `  ${JSON.stringify(french)}: ${JSON.stringify(english)},`);
  return [
    '// GENERATED by scripts/build-texts.ts from src/texts/. Do not edit: change the catalogues,',
    '// then run `npm run texts:build`.',
    '// prettier-ignore',
    'export const english: Readonly<Record<string, string>> = Object.freeze({',
    ...lines,
    '});',
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { dictionary, faults } = await buildDictionary();
  if (faults.length) {
    console.error(faults.join('\n'));
    process.exit(1);
  }
  const source = dictionarySource(dictionary);
  if (process.argv.includes('--check')) {
    const onDisk = await readFile(DICTIONARY, 'utf8').catch(() => '');
    if (onDisk !== source) {
      console.error(`${DICTIONARY} is not up to date: run \`npm run texts:build\`.`);
      process.exit(1);
    }
  } else await writeFile(DICTIONARY, source);
  console.log(JSON.stringify({ texts: dictionary.size, file: DICTIONARY }));
}
